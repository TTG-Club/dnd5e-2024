/**
 * Запасной индекс цвета — хэш от id. Нужен, когда состав мира недоступен
 * (клиент ещё не получил мир) или пользователя в нём уже нет: цвет всё равно
 * должен быть стабильным, пусть и без гарантии несовпадения.
 *
 * @param userId - ID пользователя
 * @returns индекс в палитре
 */
function hashColorIndex(userId: string): number {
  let colorHash = 0;

  for (let index = 0; index < userId.length; index++) {
    colorHash = ((colorHash << 5) - colorHash + userId.charCodeAt(index)) | 0;
  }

  return Math.abs(colorHash) % PARTICIPANT_COLORS.length;
}

/**
 * Возвращает цвет участника мира.
 *
 * Цвет раздаётся по МЕСТУ пользователя в составе мира, а не хэшем от его id:
 * хэш давал совпадения (у мастера и игрока мог выйти один цвет), а место в
 * списке гарантирует разные цвета, пока участников не больше, чем цветов в
 * палитре. Список берётся из мира целиком (а не из тех, кто сейчас онлайн),
 * поэтому цвет не скачет, когда кто-то выходит и заходит.
 *
 * @param userId - ID пользователя
 * @param worldUserIds - ID всех пользователей мира в порядке их состава
 * @returns hex-цвет из палитры
 */
export function resolveParticipantColor(
  userId: string,
  worldUserIds: readonly string[],
): string {
  const position = worldUserIds.indexOf(userId);

  const index =
    position === -1
      ? hashColorIndex(userId)
      : position % PARTICIPANT_COLORS.length;

  return PARTICIPANT_COLORS[index];
}
