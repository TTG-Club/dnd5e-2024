/**
 * Палитра цветов участников: 30 цветов, подобранных на максимальное различие.
 *
 * Подбор — жадный farthest-point в Oklab с симуляцией дальтонизма (матрицы
 * Machado 2009). Три условия сразу:
 * - максимум взвешенного расстояния (норма, дейтеранопия, протанопия);
 * - пол по протан/дейтеранопии — ни одна пара не должна слиться для дальтоника;
 * - пол по РАЗНИЦЕ ОТТЕНКА — иначе оптимизатор охотно ставит рядом «тот же цвет,
 *   но светлее» (тёмно-синий и голубой), что глазом читается как один цвет.
 * Затравка — Okabe–Ito по одному представителю оттенка, без чёрного (карта
 * тёмная), без розового (при дейтеранопии сливается с зелёным).
 *
 * ПОРЯДОК ЗНАЧИМ: цвета раздаются по нему, и первые — самые контрастные. Для
 * реального состава партии (до 10 человек) минимальное расстояние держится
 * ≈0.12 в Oklab при обычном зрении и ≈0.10 при протан/дейтеранопии; дальше
 * палитра неизбежно уплотняется — цветов, различимых при дальтонизме, физически
 * не бывает много.
 *
 * Менять список руками НЕЛЬЗЯ: он собран `scripts/build-participant-palette.mjs`
 * — правьте условия там и вставляйте вывод целиком, иначе гарантия различимости
 * пропадает молча.
 */
