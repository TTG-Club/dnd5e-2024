/**
 * Серверный гейт размеченного содержимого: журнал и описания предметов.
 *
 * ⚠️ Это НЕ санитайзер и не замена ему. Безопасность вывода обеспечивает
 * клиентский `sanitizeRichHtml` — он вырезает всё, чего нет в allowlist, прямо
 * перед показом. Здесь другая задача: не дать заведомо вредоносному
 * содержимому вообще попасть в базу.
 *
 * Почему отклонение, а не переписывание. Содержимое хранится в Markdown, и
 * переписывать его на сервере значит молча портить текст автора (в разметке
 * законно встречаются `<`, `>` и слова вроде «script»). Отклонение честнее:
 * пользователь видит, что именно не принято, и правит сам.
 *
 * Почему список маркеров узкий. Он ловит крафт WS-сообщения в обход интерфейса
 * — то есть намеренную попытку, а не опечатку. Обойти его вариациями вроде
 * `<scr\nipt` можно, и это НЕ страшно: настоящий барьер — санитайзер вывода
 * (`sanitizeRichHtml`), который разбирает разметку через `DOMParser` и
 * оставляет только allowlist. Расширять список ценой ложных срабатываний на
 * живом тексте не нужно.
 *
 * ⚠️ Разбор Markdown в журнале идёт с `html: true` — это осознанно: редактор
 * (TipTap) сохраняет подчёркивание, ссылку на другой журнал и объединённые
 * ячейки таблицы СЫРЫМ HTML, и с `html: false` читатель видел бы их текстом.
 * Санитайзер вывода режет лишнее независимо от этой настройки.
 *
 * @module richContentGuard
 */

/**
 * Признаки, при которых содержимое не принимается.
 *
 * Каждый — про исполнение кода, а не про разметку вообще:
 * - `<script` и `<iframe` — прямая вставка исполняемого контекста;
 * - `on…=` — обработчик события в атрибуте (`onerror`, `onload`, `onclick`);
 * - `javascript:` — схема, исполняющая код по клику.
 */
const DANGEROUS_PATTERNS: readonly RegExp[] = [
  /<\s*script\b/i,
  /<\s*iframe\b/i,
  /\bon[a-z]+\s*=/i,
  /javascript\s*:/i,
];

/**
 * Текст отказа для пользователя.
 *
 * Говорит о причине, а не о сбое: «ошибка сохранения» отправила бы человека
 * искать проблему не там.
 */
export const RICH_CONTENT_REJECTED_MESSAGE =
  'Содержимое содержит недопустимые элементы';

/**
 * Содержит ли текст признаки исполняемого содержимого.
 *
 * @param value - проверяемая строка
 * @returns true, если содержимое принимать нельзя
 */
export function hasDangerousRichContent(
  value: string | null | undefined,
): boolean {
  if (!value) {
    return false;
  }

  return DANGEROUS_PATTERNS.some((pattern) => pattern.test(value));
}

/**
 * Проверяет набор строк одного документа (заголовок, страницы, описание).
 *
 * @param values - строки, которые пользователь прислал на запись
 * @returns true, если хотя бы одна не проходит проверку
 */
export function hasDangerousRichContentIn(
  values: readonly (string | null | undefined)[],
): boolean {
  return values.some((value) => hasDangerousRichContent(value));
}
