/**
 * Контракт состояний (Conditions).
 *
 * Определяет метаданные для регистрации состояний/эффектов,
 * специфичных для игровой системы (отравлен, оглушён, невидим).
 *
 * @module contracts/conditions
 */

/**
 * Метаданные состояния (condition).
 */
export interface ConditionDefinition {
  /** Уникальный ключ состояния (например, 'poisoned', 'stunned') */
  key: string;
  /** Человекочитаемое название */
  label: string;
  /** Иконка (формат: 'tabler:icon-name' or 'ttg:icon-name') */
  icon: string;
  /** Описание эффекта */
  description: string;
  /** ID системы-владельца */
  systemId: string;
  /** Путь к кастомной SVG-иконке (имеет приоритет над icon) */
  customImage?: string;
  /**
   * Рисовать значок КРУПНО поверх всей фишки, а не ячейкой в сетке статусов.
   *
   * Для состояний, которые описывают саму сущность целиком, а не временную
   * помеху (у D&D 5e это «Мёртв»): ячейка в 1/5 токена такое не доносит, её
   * теряют среди прочих значков. Оверлей на токене один — если оверлейных
   * состояний вдруг несколько, показывается первое по порядку системы.
   */
  overlay?: boolean;
}
