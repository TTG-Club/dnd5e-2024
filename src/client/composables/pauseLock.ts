/**
 * На паузе не действуют. Мастер останавливает игру — и всё, что меняет бой,
 * ждёт: каст персонажа и существа, удар оружием и действие существа,
 * «Применить» у умения и «Использовать» у предмета, кнопка «При действии»,
 * «Вырваться».
 *
 * Приложение на паузе морозит карту и боевой канал: урон и эффекты не
 * проходят, шаблон области не ставится. Без своей проверки действие доходило
 * бы до этого отказа уже начатым — с открытым окном броска, заданным вопросом
 * или потраченным зарядом. Поэтому вход действия останавливается сам, второй
 * инструкцией — сразу за проверкой правки листа (`refuseWhileSheetEditing`).
 *
 * Паузой НЕ останавливается то, что боя не меняет: правка листа, отдых,
 * переключатели умений и предметов, броски проверок и кубики в чат. Измерять
 * и ставить шаблоны инструментом сцены на паузе можно — это решает
 * приложение, не система.
 *
 * Свободен от паузы тот, кого от неё освобождает приложение: мастер и роль с
 * правом управлять паузой (`worldStore.canPerformActions`).
 */

import { useWorldStore } from '@/stores/worldStore';

import { useSystemToastStore } from '../stores/systemToastStore';
import { PAUSE_LOCK_LABELS } from '../ui/actor/constants';

/**
 * Останавливает действие, пока игра на паузе, и говорит почему. Отказ ничего
 * не тратит и ничего не пишет.
 *
 * @returns `true`, если действие надо остановить
 */
export function refuseWhilePaused(): boolean {
  if (useWorldStore().canPerformActions) {
    return false;
  }

  useSystemToastStore().add({
    title: PAUSE_LOCK_LABELS.title,
    description: PAUSE_LOCK_LABELS.description,
    color: 'warning',
  });

  return true;
}
