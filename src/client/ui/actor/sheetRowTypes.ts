/**
 * Плитка параметра в строке списка на листе: короткая подпись под значением и
 * признаки показа.
 *
 * Общая для снаряжения и заклинаний — строки обеих вкладок читаются одинаково.
 * Собирает плитки вкладка (значения зависят от характеристик актёра), а строка
 * их только рисует через `SheetRowStats`.
 */
export interface SheetRowStat {
  /** Ключ плитки — по нему строка узнаёт, какую именно нажали */
  key: string;
  /** Короткая подпись под значением («Атака», «КД», «фнт.») */
  label: string;
  /** Значение плитки */
  value: string;
  /** Полная расшифровка по наведению */
  tooltip?: string;
  /** Боевой параметр — тёплая заливка вместо обычной */
  accent?: boolean;
  /** Плитка бросается по нажатию: становится кнопкой */
  rollable?: boolean;
}
