/**
 * Контракт очереди повышения уровней: её собирает окно повышения
 * ({@link LevelUpModal}), а проходит по ней лист, открывая мастер класса на
 * каждом шаге. Тип общий, чтобы форма шага описывалась в одном месте — иначе
 * новое поле пришлось бы дописывать и в окне, и в листе.
 */

/** Шаг очереди: какой класс и до какого уровня вести */
export interface WizardQueueStep {
  /** Ключ класса */
  classKey: string;
  /**
   * Пак записи класса; пусто — запись сохранена до появления поля и ищется по
   * одному ключу.
   */
  packId?: string;
  /** Уровень, который получают на этом шаге */
  targetLevel: number;
}
