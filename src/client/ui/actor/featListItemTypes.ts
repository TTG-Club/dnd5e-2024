import type { SourceDefinition } from '@vtt/shared';

/**
 * Минимальный набор полей, необходимых для отображения черты в списке.
 *
 * Общий для всей тройки компонентов: `FeatListItem` (обёртка с drag/контекстным
 * меню) и двух её представлений — `FeatListItemSheet` и
 * `FeatListItemCompendium`. Обёртка передаёт `item` в оба представления как
 * есть, поэтому её тип обязан удовлетворять обоим.
 *
 * Раньше интерфейс был объявлен трижды, локально в каждом файле, и формы
 * разошлись: у обёртки `source` был `string`, у представления компендиума —
 * `SourceDefinition`. Одноимённые, но неродственные типы — проброс `item`
 * переставал проверяться (TS2719). Один источник закрывает это по построению.
 */
export interface FeatDisplayItem {
  id: string;
  name: string;
  nameEn?: string;
  /** Ключ источника-книги — аббревиатура в нижнем регистре */
  sourceKey?: string;
  /** Определение источника, вписанное вместе с записью */
  source?: SourceDefinition;
  /** Происхождение выданной особенности (класс/вид) — для бейджа */
  grantedBy?: string;
  repeatable?: boolean;
}
