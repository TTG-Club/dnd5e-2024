export function clampVisionAngle(value: number): number {
  if (!Number.isFinite(value)) {
    return TOKEN_VISION_ANGLE_DEFAULT;
  }

  return Math.min(
    Math.max(Math.round(value), TOKEN_VISION_ANGLE_MIN),
    TOKEN_VISION_ANGLE_MAX,
  );
}

