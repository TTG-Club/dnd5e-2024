<script setup lang="ts">
  /**
   * Кнопка «Добавить» в шапке раздела — одна на всю мастерскую.
   *
   * Своим компонентом, потому что размер и вид кнопки обязаны совпадать во всех
   * разделах: пока каждый редактор рисовал свою, они разошлись — где `block` во
   * всю ширину под списком, где `xs` слева, где `sm` с отступом. Здесь у кнопки
   * одно описание, и «одинаково везде» перестаёт зависеть от того, кто её
   * добавил последним.
   *
   * Нажатие компонент не обрабатывает: `@click` долетает до кнопки сквозным
   * атрибутом, и раздел остаётся хозяином того, что добавляется.
   */
  defineProps<{
    /** Подпись кнопки: «Добавить дар», «Добавить ресурс». */
    label: string;
  }>();
</script>

<template>
  <UButton
    icon="tabler:plus"
    :label="label"
    color="primary"
    variant="soft"
    size="xs"
    class="shrink-0"
  />
</template>
