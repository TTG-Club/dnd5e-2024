/**
 * Строки списка в окнах выбора из компендиумов.
 *
 * Общее у обоих окон — того, что выдаёт вид/класс/предысторию на лист, и того,
 * что возвращает ссылку на запись: в режиме «все компендиумы» одна и та же
 * запись приезжает из нескольких паков (рабочего и его тестовой копии) и стоит
 * отдельной строкой. Отсюда и общие правила: чем строка адресуется и в каком
 * порядке строки идут.
 */

/**
 * Ключ строки списка: пак вместе с ключом записи.
 *
 * Одним ключом записи копии не различить — отметка с одной перекинулась бы на
 * другую, а на лист ушла бы не та, которую выбрали.
 *
 * @param packId - идентификатор компендиума
 * @param entryKey - ключ записи внутри компендиума
 * @returns ключ строки
 */
export function pickerRowId(packId: string, entryKey: string): string {
  return `${packId}::${entryKey}`;
}

/**
 * Строки по названию — порядок режима «все компендиумы».
 *
 * Без него список идёт паками, и копии одной записи расходятся на экран друг от
 * друга: сравнить их нечем. Сортировка устойчива, поэтому у одинаковых названий
 * сохраняется порядок паков левой колонки. Исходный список не трогаем — он
 * собран из массивов, которые окну не принадлежат.
 *
 * @param rows - строки списка
 * @returns новый список, упорядоченный по названию
 */
export function sortPickerRowsByName<TRow extends { name: string }>(
  rows: TRow[],
): TRow[] {
  return [...rows].sort((first, second) =>
    first.name.localeCompare(second.name, 'ru'),
  );
}
