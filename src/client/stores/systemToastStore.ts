/**
 * Всплывающие уведомления системы для кода, который выполняется не в `setup`.
 *
 * `useToast()` Nuxt UI достаёт своё состояние через `inject`, а он работает
 * только во время `setup` компонента. Обработчик клика, кнопка панели быстрого
 * доступа и ответ окна выбора выполняются позже — там вызов молча глушится
 * предупреждением Vue, и человек не видит, почему ничего не произошло.
 *
 * Хранилище Pinia собирается внутри контекста приложения, поэтому `useToast()`
 * в его теле работает, а само хранилище можно звать откуда угодно. Тот же приём
 * у хоста — хранилище обновлений компендиума.
 *
 * @module client/stores/systemToastStore
 */

import { useToast } from '@nuxt/ui/composables';
import { defineStore } from 'pinia';

/**
 * Хранилище уведомлений системы. Своего состояния у него нет — только действие
 * `add`, которое показывает уведомление Nuxt UI из любого места.
 *
 * Ключ с приставкой системы: ключи хранилищ — общее пространство с хостом.
 *
 * @returns хранилище с действием `add`
 */
export const useSystemToastStore = defineStore(
  'dnd5e-2024:system-toast',
  () => {
    const toast = useToast();

    return { add: toast.add };
  },
);
