/**
 * Копия данных сущности для правил, которые пишут в неё на месте.
 *
 * Движок меняет сущность прямо (урон, срабатывания, серия спасбросков): так
 * устроен контракт сервера. Клиенту и серверу, которые не должны трогать
 * оригинал, нужна глубокая копия — одна точка вместо `JSON.parse` по месту.
 *
 * @module system/dnd/dataClone
 */

/**
 * Глубокая копия чистых данных. JSON, а не `structuredClone`: на клиенте
 * сущность приходит реактивным прокси стора, и `structuredClone` его не берёт.
 * Сущности — чистый JSON, так что копия без потерь.
 *
 * @param value - данные сущности
 * @returns независимая копия того же вида
 */
export function cloneEntityData<T>(value: T): T {
  const copy: T = JSON.parse(JSON.stringify(value));

  return copy;
}
