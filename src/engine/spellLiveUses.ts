/**
 * Заряды заклинания на листе в момент каста.
 *
 * Отдельным модулем: правило нужно и заклинаниям персонажа, и блокам
 * заклинаний существа, а те и другие друг друга не импортируют.
 */

import type { Spell } from './dndEntities.js';

/**
 * Заклинание с зарядами, какие они сейчас на листе. Вход каста (строка листа,
 * ссылка горячей панели) приносит заклинание, каким оно было при отрисовке;
 * заряд за это время мог списать другой вход, и проверка по копии пускала
 * каст без ограничения.
 *
 * Меняются только заряды и только у заклинания, которое ведёт их и на листе:
 * собранное на лету (выданное чертой) идёт как пришло.
 *
 * @param spells - заклинания листа сейчас
 * @param spell - заклинание, каким его принёс вход
 * @returns заклинание с зарядами листа
 */
export function withLiveSpellUses(
  spells: readonly Spell[] | undefined,
  spell: Spell,
): Spell {
  const live = spells?.find((entry) => entry.id === spell.id);

  return spell.uses && live?.uses ? { ...spell, uses: live.uses } : spell;
}
