/**
 * Типы данных черты (feat) — всё, что черта выдаёт сверх имени и описания.
 *
 * Черта хранится как `GameItem` с `type: 'feat'`; её механические «дары»
 * (владения, языки, защиты, повышение характеристик, предусловия, выдаваемые
 * заклинания) лежат во вложенном блобе `GameItem.featData` — по аналогии с тем,
 * как вид хранит {@link SpeciesDefinition} в `GameItem.speciesData`. Активные
 * эффекты черты живут на верхнем уровне `GameItem.activeEffects` (общая для всех
 * предметов колонка), поэтому в {@link FeatData} их нет.
 */

import type { AbilityType, SkillType } from '@vtt/shared';

import type { CounterRecovery } from './classTypes.js';
import type { ConditionKey } from './conditionKeys.js';
import type { DamageDefenseKind } from './damageConstants.js';
import type { DamageDefenseEntry, GrantedSpellRef } from './speciesTypes.js';

/**
 * Повышение характеристик, выдаваемое чертой.
 *
 * - `fixed` — фиксированные прибавки (напр. `{ strength: 1 }`).
 * - `choice` — прибавка на выбор: `+amount` к `count` характеристикам из набора
 *   `from` (пусто = любая). Выбор делается игроком при применении и потому не
 *   применяется автоматически на дропе — выводится как подсказка.
 */
export interface FeatAbilityScoreIncrease {
  fixed?: Partial<Record<AbilityType, number>>;
  choice?: {
    amount: number;
    count: number;
    from?: AbilityType[];
  };
  /**
   * Ключ выбора ({@link FeatChoice.key}), к которому привязано повышение: характеристика
   * берётся оттуда, а не спрашивается второй раз. Так устроен «Устойчивый» — он поднимает
   * ту характеристику, спасбросками которой персонаж овладел.
   */
  fromChoiceKey?: string;
  /**
   * Предел, выше которого характеристику не поднять: 20 у обычных черт, 30 у эпических
   * даров — тем они и отличаются. Показывается в сводке даров; сам лист характеристики
   * не ограничивает нигде (ни классовое повышение, ни ручные бонусы), поэтому предел
   * остаётся справкой для мастера, а не жёстким правилом.
   */
  upto?: number;
}

/**
 * Ссылка на запись справочника в требовании черты: слаг страницы плюс снимок
 * названия. Название хранится рядом, чтобы требование читалось без обращения к
 * компендиуму — и не превращалось в пустую строку, когда записи нет.
 */
export interface FeatPrerequisiteRef {
  /** Слаг страницы записи на сайте (`wizard-phb`) */
  url: string;
  /** Название на момент сохранения */
  name: string;
}

/**
 * Требование к значению характеристики: «Сила или Ловкость 13+».
 * `anyOf` — именно «любая из», а не «все»: в книгах это всегда так.
 */
export interface FeatAbilityRequirement {
  anyOf: AbilityType[];
  minValue: number;
}

/**
 * Классовое умение, которого требует черта. Набор закрыт: в справочнике черт
 * встречаются только эти четыре требования.
 */
export type FeatClassFeatureRequirement =
  'spellcasting' | 'pactMagic' | 'fightingStyle' | 'weaponMastery';

/**
 * Предусловие (требование) черты.
 *
 * Проверяется мягко: лист показывает, чему персонаж не соответствует, но взять
 * черту не мешает — за столом мастер разрешает исключения, а запрет вдобавок
 * ломал бы уже собранных персонажей.
 *
 * Заполненные поля соединяются по «И», множественность внутри поля — по «ИЛИ».
 * Поля {@link abilities}, {@link minLevel} и {@link spellcasting} — исходная,
 * упрощённая форма; она остаётся рабочей (её пишет редактор черты) и
 * проверяется наравне с разобранными полями.
 */
export interface FeatPrerequisite {
  /** Минимальные значения характеристик (напр. `{ strength: 13 }`). */
  abilities?: Partial<Record<AbilityType, number>>;
  /** Требования вида «Сила ИЛИ Ловкость 13+», которые {@link abilities} не выражает. */
  abilityRequirements?: FeatAbilityRequirement[];
  /** Минимальный суммарный уровень персонажа. */
  minLevel?: number;
  /** Требуется ли способность творить заклинания. */
  spellcasting?: boolean;
  /** Классовые умения, любого из которых достаточно. */
  classFeatures?: FeatClassFeatureRequirement[];
  /** Черты, которые нужно иметь. */
  feats?: FeatPrerequisiteRef[];
  /** Классы, любого из которых достаточно. */
  classes?: FeatPrerequisiteRef[];
  /** Виды, любого из которых достаточно. */
  species?: FeatPrerequisiteRef[];
  /** Предыстории, любой из которых достаточно. */
  backgrounds?: FeatPrerequisiteRef[];
  /** Владение доспехами (ключи: light/medium/heavy/shield). */
  armorProficiency?: string[];
  /** Сеттинг кампании — показывается, но не проверяется. */
  campaign?: string;
  /**
   * Нужна любая черта метки дракона (Эберрон). Конкретная черта не важна, поэтому
   * ссылкой такое требование не выразить: проверяется по названию взятых черт.
   */
  anyDragonmark?: boolean;
  /** Произвольный текст требования (напр. «Эльф или полуэльф»). */
  text?: string;
}

/**
 * Прибавка к максимуму хитов от черты.
 *
 * Итог: `flat + perAcquisitionLevel × уровень взятия +
 * perLevelAfterAcquisition × (текущий уровень − уровень взятия)`.
 *
 * Из-за двух последних слагаемых лист обязан помнить **уровень, на котором
 * черту взяли**: «Крепкий» на 4 уровне и он же на 12 дают разную прибавку
 * навсегда. Уровень хранится в {@link AppliedFeatMeta.acquisitionLevel}.
 */
export interface FeatHitPointsModifier {
  /** Постоянная прибавка */
  flat?: number;
  /** Прибавка за каждый уровень персонажа на момент взятия черты */
  perAcquisitionLevel?: number;
  /** Прибавка за каждый уровень, полученный после взятия черты */
  perLevelAfterAcquisition?: number;
}

/**
 * Постоянное изменение скоростей в футах.
 *
 * Новый вид движения задаётся либо числом («Дар совершенного полёта» — полёт
 * 40), либо флагом «равна скорости ходьбы» («Атлет» — лазание, «Каменные
 * крылья» — полёт).
 */
export interface FeatSpeedModifier {
  /** Прибавка к скорости ходьбы */
  walkBonus?: number;
  fly?: number;
  climb?: number;
  swim?: number;
  flyEqualsWalk?: boolean;
  climbEqualsWalk?: boolean;
  swimEqualsWalk?: boolean;
}

/**
 * Чувство, которое даёт черта.
 *
 * Тёмное зрение сюда НЕ входит: у него своё поле {@link FeatData.darkvision},
 * и оно единственное доходит до зрения токена — остальные чувства приложение
 * пока не умеет (см. README, § «Чего не хватает для полноценного SDK», п. 12).
 * Поэтому они показываются в шапке листа справкой, но на видимость сцены не
 * влияют.
 */
export type FeatSenseKind = 'blindsight' | 'truesight' | 'tremorsense';

/** Чувство с дистанцией в футах: слепое зрение 10, истинное зрение 60. */
export interface FeatSenseGrant {
  type: FeatSenseKind;
  /** Дистанция в футах */
  range: number;
}

/**
 * Постоянные модификаторы листа, которые даёт черта: то, что она меняет в шапке
 * и в блоке защит раз и навсегда, без условий и активации.
 *
 * Условные эффекты сюда не идут: «Оборона» даёт +1 к КД только в доспехе,
 * «Налётчик» ускоряет только на действие Рывок. Такое остаётся в описании и
 * при необходимости заводится своим активным эффектом с условием.
 */
export interface FeatModifiers {
  /** Прибавка к максимуму хитов */
  hitPoints?: FeatHitPointsModifier;
  /** Изменение скоростей */
  speed?: FeatSpeedModifier;
  /** Постоянная прибавка к классу доспеха */
  armorClassBonus?: number;
  /** Чувства с дистанцией (кроме тёмного зрения — см. {@link FeatSenseGrant}) */
  senses?: FeatSenseGrant[];
  /** Дальность телепатии в футах («Дар Общения» — 120) */
  telepathyRange?: number;
  /**
   * Легаси-псевдоним первой записи {@link FeatData.damageDefenseChoices} с видом
   * `resistance`: до появления списка защита по выбору могла быть только
   * сопротивлением и только одна. Читается, когда списка нет вовсе, — записи,
   * сделанные до правки, продолжают работать без пересохранения.
   */
  resistanceFromChoiceKey?: string;
  /** К броску инициативы прибавляется бонус мастерства («Бдительный») */
  initiativeProficiencyBonus?: boolean;
  /**
   * Постоянная числовая прибавка к инициативе. Складывается с
   * {@link initiativeProficiencyBonus}, если стоят оба.
   */
  initiativeBonus?: number;
}

/**
 * Что выбирает игрок при взятии черты.
 *
 * Выборы по ходу игры («выберите существо в пределах 30 футов») сюда не входят: лист их
 * не запоминает, они остаются в описании. Повышение характеристик — тоже выбор, но у
 * него своя модель ({@link FeatAbilityScoreIncrease}); если оно применяется к уже
 * выбранному значению, как у «Устойчивого», выбор описывается здесь, а повышение
 * ссылается на него через {@link FeatChoice.key}.
 */
export type FeatChoiceType =
  | 'ability'
  | 'savingThrow'
  | 'skill'
  | 'tool'
  | 'language'
  | 'damageType'
  | 'spell'
  | 'cantrip'
  | 'spellList'
  | 'spellcastingAbility'
  | 'weapon'
  /**
   * Оружие, приёмом которого персонаж овладевает: «Оружейный приём» воина
   * называет три ВИДА ОРУЖИЯ, а приём у каждого свой. Значение — ключ оружия.
   */
  | 'weaponMastery'
  /**
   * Сам приём (`cleave`, `topple`, …) — так его выбирает «Тактический мастер»:
   * приём подменяется на Толкание, Изнурение или Замедление независимо от того,
   * каким оружием бьют. Значение — ключ приёма из `WEAPON_MASTERIES`.
   */
  | 'masteryProperty'
  | 'armor'
  /**
   * @deprecated Смешанный набор задаётся списком {@link FeatChoice.types}.
   * Значение осталось ради записей, сохранённых до его появления: движок
   * разворачивает его в «навык + инструмент».
   */
  | 'skillOrTool'
  | 'option'
  /**
   * Черта компендиума: умение класса даёт выбрать черту — боевой стиль на
   * первом уровне воина, общую черту вместо повышения характеристик. Значение —
   * {@code id} записи черты в компендиуме; пул задают {@link FeatChoice.options}
   * (перечень) и {@link FeatChoice.featCategories} (категории).
   */
  | 'feat';

/** Допустимое значение выбора: ключ своего словаря плюс подпись для игрока. */
export interface FeatChoiceOption {
  value: string;
  name?: string;
}

/** Чем ограничен выбор заклинания или заговора. */
export interface FeatChoiceSpellFilter {
  /** Точный уровень; 0 — заговор */
  level?: number;
  /** Наибольший допустимый уровень */
  maxLevel?: number;
  /** Школы магии, любой из которых достаточно */
  schools?: string[];
  /** Классы, из списков заклинаний которых можно выбирать */
  classes?: FeatPrerequisiteRef[];
  /**
   * Те же классы каноническими ключами (`wizard`) — по ним пул сверяется со
   * `spell.classKeys`. Слаг страницы из {@link classes} для сверки не годится: он несёт
   * суффикс источника.
   */
  classKeys?: string[];
  /**
   * Ключ выбора ({@link FeatChoice.key}), из ответа на который берётся класс.
   * «Посвящённый в магию» сперва спрашивает список — жреца, друида или волшебника, — и
   * только потом даёт выбрать из него заговоры: пул сужается до одного выбранного класса,
   * а не до всех трёх. Ссылка устроена так же, как {@link FeatAbilityScoreIncrease.fromChoiceKey}.
   */
  classesFromChoiceKey?: string;
  /** Время накладывания (`ritual`, `action`, …) */
  castingTime?: string;
}

/**
 * Защита от типа урона, который называет игрок.
 *
 * Ссылка на выбор плюс исход, который этот выбор даёт: на момент записи черты
 * тип урона ещё не назван, а вид защиты известен всегда. Списком, а не одним
 * полем: черта может дать разными выборами и сопротивление, и иммунитет.
 */
export interface FeatDamageDefenseChoice {
  /** Ключ выбора ({@link FeatChoice.key}), ответ на который даёт тип урона */
  choiceKey: string;
  /** Что выбранный тип урона получает */
  kind: DamageDefenseKind;
}

/** Выбор, который игрок делает в момент взятия черты. */
export interface FeatChoice {
  /**
   * Стабильный ключ в пределах черты: по нему лист хранит сделанный выбор, и на него
   * ссылаются повышение характеристик и сопротивление по выбору.
   */
  key: string;
  /**
   * Основной вид выбора. Когда вид один — он здесь и есть; когда их несколько,
   * здесь первый, а полный набор в {@link types}. Так запись остаётся читаемой
   * для тех, кто про смешанные наборы не знает (выгрузка компендиума шлёт
   * только это поле).
   */
  type: FeatChoiceType;
  /**
   * Полный набор видов, когда выбирают из нескольких справочников сразу:
   * «Умелый» берёт три штуки вперемешку из навыков и инструментов. Задан только
   * при нескольких видах; куда лечь выбранному, решает принадлежность самого
   * значения ({@link resolveFeatChoiceValueType}).
   *
   * Смешивать можно только виды со справочником правил. Оружие, приёмы оружия,
   * заклинания и «вариант» описаны данными мира или компендиума — по значению их
   * не разложить, и в набор они не входят.
   */
  types?: FeatChoiceType[];
  /** Подпись для игрока («Выберите навык») */
  label?: string;
  /** Сколько значений выбирают; по умолчанию одно */
  count?: number;
  /** Количество равно бонусу мастерства и растёт вместе с ним («Ритуальный заклинатель») */
  countEqualsProficiencyBonus?: boolean;
  /** Допустимые значения; пусто — любое значение своего типа */
  options?: FeatChoiceOption[];
  /** Ограничение выбора заклинания */
  spellFilter?: FeatChoiceSpellFilter;
  /** Только то, чем персонаж ещё не владеет */
  onlyIfNotProficient?: boolean;
  /** Только то, чем персонаж уже владеет («Знаток») */
  onlyIfProficient?: boolean;
  /** Владеет выбранным — получает компетентность вместо владения */
  expertiseIfProficient?: boolean;
  /** Что даёт выбор; по умолчанию владение */
  grants?: 'proficiency' | 'expertise';
  /** Выбор пересматривается на продолжительном отдыхе («Мастер оружия») */
  rechooseOnLongRest?: boolean;
  /**
   * Уровень персонажа, с которого выбор открывается; нет — сразу.
   *
   * Нужен умению, которое спрашивает одно и то же не один раз: компетентность
   * плут получает на 1 уровне и ещё раз на 6, бард — на 2 и на 9. Второго
   * умения под это в книге нет, повтор описан строкой роста, — поэтому уровень
   * стоит у самого выбора.
   */
  requiredLevel?: number;
  /**
   * Категории черт, из которых выбирают, — подписями записи компендиума
   * (`Feature.category`, напр. «Боевой стиль»). Только у типа `feat`; пусто —
   * категория не ограничена. Перечень {@link options} сужает пул сильнее.
   */
  featCategories?: string[];
  /**
   * Ступени количества по уровням: ключ — уровень строкой, значение — сколько
   * ВСЕГО выбрано к этому уровню. Пусто — количество не растёт и задано
   * {@link count}.
   *
   * Ступень называет итог, а не прибавку: оружейных приёмов у воина три с 1
   * уровня, четыре с 4, пять с 10. Мастер повышения уровня спрашивает разницу
   * с предыдущей ступенью, а колонка таблицы показывает сам ряд.
   */
  scaling?: Record<string, number>;
  /**
   * Показывать количество колонкой таблицы прогрессии класса. Ряд по уровням у
   * выбора уже задан ступенями, и колонкой его не набирают второй раз.
   */
  showInTable?: boolean;
  /**
   * Краткая подпись колонки таблицы; пусто — берётся {@link label}. Подпись
   * выбора — это вопрос игроку, а в шапке таблицы нужно существительное.
   */
  shortName?: string;
}

/**
 * Черта, которую запись выдаёт без выбора: умение класса кладёт её на лист
 * само, как предыстория кладёт черту происхождения.
 */
export interface FeatGrantedRef {
  /** `id` записи черты в компендиуме */
  featId: string;
  /** Название на момент выгрузки — показать, даже когда записи в паках нет */
  name: string;
}

/**
 * Что лист запоминает о применённой черте сверх её даров.
 *
 * Живёт на самой особенности-черте актора рядом с `featData`, потому что это
 * состояние конкретного применения, а не свойство черты из справочника.
 */
export interface AppliedFeatMeta {
  /**
   * Суммарный уровень персонажа на момент взятия черты. Нужен прибавке к хитам
   * ({@link FeatHitPointsModifier}); у черт, взятых до появления поля,
   * отсутствует — тогда прибавка считается от текущего уровня.
   */
  acquisitionLevel?: number;
  /**
   * Что игрок выбрал при взятии черты: ключ выбора ({@link FeatChoice.key}) → выбранные
   * значения. Хранится на применённой черте, а не на акторе: по нему выбор откатывается
   * вместе с чертой и пересматривается на отдыхе.
   */
  choices?: Record<string, string[]>;
  /**
   * Ключ предыстории, которая выдала эту черту. Сама черта остаётся обычной чертой со
   * своим провенансом ({@code feat:<id>}) — метка лишь говорит, откуда она взялась:
   * по ней замена предыстории снимает выданную черту вместе с её дарами, а лист
   * показывает игроку, что черта не выбрана свободно.
   */
  grantedByBackgroundKey?: string;
  /**
   * Ключ вида, который выдал эту черту (выбором дара «Универсальность» человека или
   * перечнем выдаваемых черт). Как и у предыстории, сама черта остаётся обычной чертой
   * со своим провенансом ({@code feat:<id>}) — метка лишь говорит, откуда она взялась:
   * по ней смена и удаление вида снимают выданную черту вместе с её дарами.
   */
  grantedBySpeciesKey?: string;
}

/**
 * Полные «грант»-данные черты. Переносятся на актора при применении черты
 * (перетаскивании на лист); хранятся в `GameItem.featData`.
 */
export interface FeatData {
  /** Дискриминант блоба (для единообразия со SpeciesDefinition). */
  type: 'feat';
  /** Владение навыками (фиксированный набор). */
  skillProficiencies?: SkillType[];
  /** Владение спасбросками. */
  savingThrowProficiencies?: AbilityType[];
  /** Владение доспехами (ключи: light/medium/heavy/shield). */
  armorProficiencies?: string[];
  /** Владение оружием (ключи категорий/конкретного оружия). */
  weaponProficiencies?: string[];
  /**
   * Оружейные приёмы (weapon mastery, 2024) — ключи видов оружия. Отдельно от
   * {@link weaponProficiencies}: «Мастер оружия» даёт и владение, и приём, а это
   * разные списки на листе (`proficiencies.weaponMasteries`).
   */
  weaponMasteries?: string[];
  /**
   * Сами приёмы (`cleave`, `topple`, …), которыми запись наделяет безотносительно
   * оружия. Отдельно от {@link weaponMasteries}: там ключи ОРУЖИЯ, здесь ключи
   * ПРИЁМОВ, и на листе это тоже разные списки (`proficiencies.masteryProperties`).
   */
  masteryProperties?: string[];
  /** Владение инструментами (ключи). */
  toolProficiencies?: string[];
  /** Известные языки. */
  languages?: string[];
  /** Защиты от типов урона (сопротивление/иммунитет/уязвимость). */
  damageDefenses?: DamageDefenseEntry[];
  /**
   * Защиты от типов урона, которые называет игрок: «Закалённая кожа» просит
   * выбрать дробящий или рубящий и даёт к названному сопротивление. Сам тип
   * известен только после выбора, поэтому в {@link damageDefenses} такая защита
   * лечь не может. См. {@link FeatDamageDefenseChoice}.
   */
  damageDefenseChoices?: FeatDamageDefenseChoice[];
  /** Иммунитеты к состояниям. */
  conditionImmunities?: ConditionKey[];
  /** Тёмное зрение (футы, 0/undefined = нет). */
  darkvision?: number;
  /** Повышение характеристик. */
  abilityScoreIncrease?: FeatAbilityScoreIncrease;
  /** Постоянные модификаторы листа: хиты, скорости, КД, инициатива. */
  modifiers?: FeatModifiers;
  /** Выборы, которые игрок делает при взятии черты. */
  choices?: FeatChoice[];
  /** Черты, выданные без выбора; несут только умения класса. */
  grantedFeats?: FeatGrantedRef[];
  /** Предусловия (требования) черты. */
  prerequisite?: FeatPrerequisite;
  /**
   * Выдаваемые заклинания: имя + опц. связь с компендиумом (`spellId`). При
   * применении связанные заклинания авто-выдаются, как у особенностей вида.
   * См. {@link GrantedSpellRef}.
   */
  grantedSpells?: GrantedSpellRef[];
  /**
   * Заклинательная характеристика заклинаний черты. Не задана — характеристика берётся
   * от класса, как у остальных заклинаний листа. Проставляется выданным заклинаниям и
   * потому влияет на их атаку и сложность спасброска.
   */
  spellcastingAbility?: AbilityType;
  /**
   * Выданные чертой заклинания не нужно готовить. Не задано — готовить нужно: заклинание
   * ложится в книгу наравне с остальными и занимает подготовку.
   */
  grantedSpellsAlwaysPrepared?: boolean;
  /**
   * Заклинания, которые черта добавляет в список заклинаний класса — таблица
   * «Заклинания метки». Не выдача: подготовку и ячейку персонаж тратит сам,
   * поэтому отдельным полем от {@link grantedSpells}.
   * См. {@link FeatSpellListExpansion}.
   */
  spellList?: FeatSpellListExpansion;
  /**
   * Ресурсы черты со своим счётчиком: очки удачи «Удачливого», применения
   * «Целителя». См. {@link FeatCounterDefinition}.
   */
  counters?: FeatCounterDefinition[];
}

/**
 * Один список расширения — со своим уровнем доступа и своим количеством.
 *
 * Списков у черты бывает несколько, и это НЕ взаимоисключающие варианты: каждый
 * открывается на своём уровне и складывается с предыдущими. У метки дракона
 * таблица открывается ступенями, и без разбивки лист выдал бы её целиком уже на
 * первом уровне.
 */
export interface FeatSpellListGroup {
  /** Уровень персонажа, с которого список открывается; пусто — сразу */
  requiredLevel?: number;
  /**
   * Сколько заклинаний из списка берут; пусто — весь список. Формулой, а не
   * числом: у части черт количество растёт вместе с персонажем. Грамматика та
   * же, что у {@link FeatCounterDefinition.max} (`@prof`, `@level`, `@mod.<abbr>`).
   */
  count?: string;
  /** Заклинания списка */
  spells: GrantedSpellRef[];
}

/**
 * Расширение списка заклинаний класса — таблица «Заклинания метки».
 *
 * Отдельная механика от выдачи ({@link FeatData.grantedSpells}): выданное
 * заклинание персонаж знает и накладывает, а это он лишь МОЖЕТ подготовить
 * наравне с классовыми. На листе такое заклинание ложится в книгу
 * неподготовленным и заклинательную характеристику черты не наследует — оно
 * считается от класса, как остальные заклинания списка.
 */
export interface FeatSpellListExpansion {
  /** Списки заклинаний по уровням доступа */
  groups: FeatSpellListGroup[];
  /**
   * Список расширяется, только если у персонажа есть «Использование заклинаний»
   * или «Магия договора»; пусто — расширяет всегда. Так устроены все черты метки
   * дракона: без заклинательства расширять нечего.
   */
  requiresSpellcasting?: boolean;
}

/**
 * Ресурс черты — счётчик с максимумом и откатом от отдыха.
 *
 * Отличается от классового ({@link ClassCounterDefinition}) тем, что у него нет
 * ни уровня начала, ни прогрессии по уровням: черта либо взята, либо нет.
 * Максимум задаётся формулой, потому что у большинства таких ресурсов он
 * привязан к бонусу мастерства («Удачливый» — очки удачи по бонусу мастерства)
 * и обязан расти вместе с ним.
 */
export interface FeatCounterDefinition {
  /** Стабильный ключ ресурса в пределах черты */
  key: string;
  /** Название на листе («Очки удачи») */
  name: string;
  /** Краткое название для компактной плитки счётчика */
  shortName?: string;
  /**
   * Формула максимума: число либо выражение с `@prof`, `@level`, `@mod.<abbr>`
   * (см. `formulaParser`). Считается при выдаче черты и пересчитывается при
   * повышении уровня.
   */
  max: string;
  /**
   * Ступени максимума по уровням: ключ — уровень строкой, значение — максимум
   * ЦЕЛИКОМ на этом уровне, а не прибавка. Заданы — {@link max} не считается:
   * ряд, который формулой не пишется, задан ими и точнее любого выражения.
   *
   * Считаются от уровня ПЕРСОНАЖА, а не класса: ресурс приходит от записи
   * (черта, умение вида или класса), а не от класса целиком. Ресурсу, чей ряд
   * обязан идти по уровню класса, место в счётчиках класса
   * ({@link ClassCounterDefinition.progression}) — только их и отдаёт
   * компендиум.
   */
  progression?: Record<string, number>;
  /**
   * Нижняя граница максимума; нет или 0 — границы нет. Подпирает формулу снизу:
   * вдохновение барда равно модификатору Харизмы, но не меньше одного.
   */
  min?: number;
  /** Каким отдыхом восстанавливается */
  recovery: CounterRecovery;
}
