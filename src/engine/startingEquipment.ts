/**
 * Стартовое снаряжение предыстории и класса — позициями, а не строкой.
 *
 * Вариант снаряжения приезжает из компендиума в двух видах сразу: готовая
 * строка для чтения (`description`) и разбор по позициям (`items`/`coins`).
 * Строка остаётся источником показа — в ней живые ссылки на карточки; позиции
 * нужны, чтобы мастер положил предметы в инвентарь сам, а не заставлял игрока
 * перетаскивать их по одному.
 *
 * Записи без позиций (старые паки, свои предыстории) работают как раньше:
 * вариант показывается строкой, автовыдавать нечего.
 *
 * @module system/dnd/startingEquipment
 */

/** Позиция варианта стартового снаряжения. */
export interface StartingEquipmentItem {
  /**
   * Слаг страницы предмета на сайте (`dagger-phb`) — по нему позиция ищется в
   * компендиуме. Пусто — свободное уточнение вроде «древние карты»: карточки за
   * ним нет, и в инвентарь оно ложится обычным предметом по названию.
   */
  url?: string;
  /** Название предмета */
  name: string;
  /** Количество; по умолчанию 1 */
  quantity?: number;
  /** Уточнение к позиции («по вашему выбору») */
  note?: string;
}

/**
 * Вариант стартового снаряжения — общая часть предыстории и класса. Свои поля
 * (метка варианта у класса, золотая альтернатива у предыстории) остаются в их
 * собственных типах.
 */
export interface StartingEquipmentOption {
  /** Видимая строка варианта с живыми ссылками на карточки */
  description: string;
  /** Позиции варианта; пусто — автовыдавать нечего */
  items?: StartingEquipmentItem[];
  /** Количество монет варианта */
  coins?: number;
  /** Тип монет (`GC`, `SC`, …); по умолчанию золотые */
  coin?: string;
}

/** Количество позиции с поправкой на незаполненное поле. */
export function startingEquipmentQuantity(item: StartingEquipmentItem): number {
  const quantity = item.quantity;

  return quantity === undefined || quantity < 1 ? 1 : Math.round(quantity);
}

/**
 * Есть ли у варианта что выдавать автоматически. Вариант без позиций и без
 * монет — только текст: мастер покажет его, но в инвентарь ничего не положит.
 *
 * @param option - вариант снаряжения
 */
export function hasGrantableEquipment(
  option: StartingEquipmentOption,
): boolean {
  return Boolean(option.items?.length) || Boolean(option.coins);
}
