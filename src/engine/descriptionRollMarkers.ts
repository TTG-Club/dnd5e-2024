/**
 * Кнопки бросков `{@roll 1к6}` в описаниях компендиума.
 *
 * Кнопкой их делает хостовый рендерер описаний (`ItemDescriptionRenderer`).
 * Туда, где описание уходит простым текстом — сообщение в чат, всплывающая
 * подсказка `title`, — марка попала бы как есть, со скобками. Форма марки —
 * контракт рендерера хоста; сам он её наружу не отдаёт, поэтому здесь своя
 * копия шаблона.
 */

/** Кнопка броска в тексте описания: `{@roll 2к6+3}` → формула в группе 1 */
const DESCRIPTION_ROLL_MARKER_REGEX = /\{@roll ([^}]+)\}/g;

/**
 * Заменяет кнопки бросков описания их формулами: «получает {@roll 1к6} урона»
 * становится «получает 1к6 урона».
 *
 * @param text - описание из компендиума
 * @returns текст без марок бросков
 */
export function stripDescriptionRollMarkers(text: string): string {
  return text.replace(
    DESCRIPTION_ROLL_MARKER_REGEX,
    (_marker, formula: string) => formula.trim(),
  );
}
