/**
 * Реестр состояний МИРА: состояния, созданные за столом, и правки канонных.
 *
 * Лист-модуль без рантайм-импортов: его читает `conditionTemplates` (канон +
 * слияние), а наполняет клиентский слой системы. Иначе вышел бы цикл
 * `conditionTemplates` ↔ реестр.
 *
 * Источником данных выступает ГЕТТЕР, а не массив: движок инлайнится и в
 * серверный бандл, где ни `vue`, ни `pinia` нет, а клиенту нужна реактивность —
 * геттер, читающий стор, отслеживается вычисляемыми свойствами (в том числе
 * ядровыми: значки состояний на токенах). Без установленного источника (сервер,
 * загрузка до прихода записей мира) реестр пуст и остаётся один канон.
 *
 * @module engine/conditionRegistry
 */

import type { ConditionEffectTemplate } from './conditionTemplates.js';

/**
 * Состояние, заведённое в мире: справочная часть плюс шаблон эффекта.
 *
 * Ключ канонного состояния (`poisoned`) означает ПРАВКУ канона — такая запись
 * подменяет канонную в списке; любой другой ключ — своё состояние стола.
 */
export interface WorldConditionDefinition {
  /** Ключ состояния: канонный (правка) либо слаг своего состояния */
  key: string;
  /** Название на русском */
  nameRu: string;
  /** Название на английском */
  nameEn?: string;
  /** Иконка коллекции (`tabler:*`) */
  icon?: string;
  /** Картинка-значок (адрес ассета); имеет приоритет над иконкой */
  customImage?: string;
  /** Описание состояния */
  description: string;
  /** Рисовать значок крупно поверх всей фишки, а не ячейкой сетки статусов */
  overlay?: boolean;
  /** Шаблон эффекта, который состояние накладывает, пока висит на сущности */
  template: ConditionEffectTemplate;
}

/**
 * Пустой список для случая «источник не установлен».
 *
 * Константа, а не новый `[]` на каждый вызов: потребитель кэширует слияние по
 * ССЫЛКЕ на этот список, и свежий массив каждый раз сбрасывал бы кэш.
 */
const NO_WORLD_CONDITIONS: readonly WorldConditionDefinition[] = [];

/** Источник состояний мира, установленный клиентским слоем системы. */
let worldConditionsSource: (() => readonly WorldConditionDefinition[]) | null =
  null;

/**
 * Устанавливает источник состояний мира.
 *
 * @param source - геттер списка состояний мира либо `null` для сброса
 */
export function setWorldConditionsSource(
  source: (() => readonly WorldConditionDefinition[]) | null,
): void {
  worldConditionsSource = source;
}

/**
 * Читает состояния мира из установленного источника.
 *
 * Вызывается на каждом обращении, а не кэшируется: клиентский источник —
 * реактивный, и кэш заморозил бы список на первом чтении.
 *
 * @returns состояния мира (пустой список, если источник не установлен)
 */
export function readWorldConditions(): readonly WorldConditionDefinition[] {
  return worldConditionsSource?.() ?? NO_WORLD_CONDITIONS;
}
